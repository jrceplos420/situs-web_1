<h1>Cara Mengetahui Busi Motor Rusak</h1>

<p>
Busi merupakan komponen penting dalam sistem pengapian motor.
Fungsinya menghasilkan percikan api untuk membakar campuran udara dan bahan bakar di dalam ruang bakar. Jika busi bermasalah, performa mesin akan menurun bahkan motor bisa sulit dihidupkan.
</p>

<p>
Banyak pengendara tidak menyadari bahwa busi yang sudah lemah dapat menyebabkan konsumsi bahan bakar menjadi lebih boros, tenaga motor berkurang, dan mesin terasa tersendat saat berakselerasi.
</p>

<div class="info">

<h3>🔍 Tanda-Tanda Busi Rusak</h3>

<ul>

<li>Motor sulit distarter, terutama saat mesin dingin.</li>

<li>Mesin brebet ketika digas.</li>

<li>Tenaga motor terasa lemah.</li>

<li>Konsumsi bahan bakar menjadi lebih boros.</li>

<li>Ujung elektroda busi berwarna hitam pekat atau sudah aus.</li>

</ul>

</div>

<p>
Periksa kondisi busi secara berkala setiap 8.000–10.000 kilometer atau sesuai jadwal servis yang dianjurkan oleh pabrikan. Membersihkan busi hanya bersifat sementara jika kondisi elektroda sudah aus.
</p>

<p>
Saat mengganti busi, gunakan tipe yang sesuai dengan spesifikasi motor Anda. Penggunaan busi yang tidak sesuai dapat memengaruhi performa mesin dan sistem pembakaran.
</p>

<p>
Jika motor sering digunakan untuk perjalanan jauh atau kondisi jalan yang berat, pemeriksaan busi sebaiknya dilakukan lebih sering agar sistem pengapian tetap bekerja secara optimal.
</p>

<p>
Merawat busi secara rutin membuat proses pembakaran lebih sempurna, tenaga motor tetap maksimal, mesin lebih halus, dan konsumsi bahan bakar menjadi lebih hemat.
</p>

