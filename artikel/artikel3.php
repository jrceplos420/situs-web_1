<h1>Tanda Kampas Rem Motor Harus Diganti</h1>

<p>
Kampas rem merupakan salah satu komponen paling penting pada sistem pengereman.
Kondisi kampas rem yang sudah aus dapat mengurangi kemampuan motor untuk berhenti
dan meningkatkan risiko kecelakaan.
</p>

<p>
Salah satu tanda yang paling sering muncul adalah suara berdecit saat melakukan
pengereman. Bunyi tersebut biasanya muncul karena permukaan kampas rem sudah
menipis sehingga bergesekan langsung dengan piringan rem.
</p>

<p>
Selain suara, tanda lainnya adalah jarak pengereman menjadi lebih panjang,
tuas rem terasa lebih dalam saat ditekan, atau motor terasa kurang responsif
ketika direm.
</p>

<div class="info">

<h3>⚠ Kapan Harus Diganti?</h3>

<p>
Periksa kampas rem setiap servis berkala atau setiap menempuh sekitar
8.000–12.000 km tergantung cara penggunaan kendaraan.
Jangan menunggu kampas rem habis karena dapat merusak piringan rem yang
biayanya jauh lebih mahal.
</p>

</div>

<p>
Gunakan kampas rem asli atau berkualitas baik agar pengereman tetap optimal.
Penggantian kampas rem yang tepat waktu akan membuat perjalanan lebih aman,
nyaman, dan mengurangi risiko kecelakaan di jalan.
</p>

