<h1>Tips Merawat CVT Motor Matic</h1>

<p>
CVT (Continuously Variable Transmission) merupakan sistem transmisi otomatis
yang banyak digunakan pada motor matic. Agar tarikan motor tetap halus,
komponen CVT harus dirawat secara berkala.
</p>

<p>
Lakukan pembersihan rumah CVT setiap 8.000–10.000 kilometer.
Debu yang menumpuk dapat mengganggu kinerja roller dan v-belt sehingga
motor terasa bergetar saat akselerasi.
</p>

<p>
Selain membersihkan CVT, periksa juga kondisi roller, kampas kopling,
v-belt, dan mangkok kopling. Komponen yang sudah aus sebaiknya segera
diganti agar tidak merusak komponen lainnya.
</p>

<p>
Gunakan suku cadang asli dan lakukan servis di bengkel terpercaya.
Perawatan CVT yang rutin membuat motor lebih nyaman dikendarai,
hemat bahan bakar, dan memperpanjang umur transmisi.
</p>

