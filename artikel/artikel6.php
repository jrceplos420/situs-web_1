<h1>Kapan Ban Motor Harus Diganti?</h1>

<p>
Ban merupakan satu-satunya komponen motor yang langsung bersentuhan dengan jalan.
Kondisi ban sangat memengaruhi kenyamanan, kestabilan, dan keselamatan saat berkendara.
Oleh karena itu, ban harus selalu diperiksa secara rutin.
</p>

<p>
Banyak pengendara hanya mengganti ban ketika ban bocor atau pecah.
Padahal, ban yang sudah aus juga sangat berbahaya karena daya cengkeramnya terhadap jalan sudah berkurang.
Hal ini dapat meningkatkan risiko tergelincir, terutama saat jalan basah.
</p>

<div class="info">

<h3>🚨 Tanda Ban Harus Diganti</h3>

<ul>

<li>Alur ban sudah tipis atau menyentuh TWI (Tread Wear Indicator).</li>

<li>Ban mulai retak pada bagian samping.</li>

<li>Ban sering bocor karena usia pemakaian.</li>

<li>Motor terasa tidak stabil saat dikendarai.</li>

<li>Permukaan ban sudah tidak rata.</li>

</ul>

</div>

<p>
Idealnya ban motor diganti setiap 15.000 hingga 25.000 kilometer,
tergantung jenis ban dan kondisi jalan yang sering dilalui.
Jika sering melewati jalan rusak atau membawa beban berat,
umur ban biasanya lebih pendek.
</p>

<p>
Pastikan tekanan angin ban selalu sesuai rekomendasi pabrikan.
Tekanan angin yang terlalu rendah maupun terlalu tinggi dapat mempercepat keausan ban
dan membuat motor kurang nyaman dikendarai.
</p>

<p>
Selain itu, lakukan pemeriksaan ban sebelum melakukan perjalanan jauh.
Periksa apakah ada benda tajam yang menancap, benjolan pada ban,
atau kerusakan lain yang dapat membahayakan keselamatan.
</p>

<p>
Dengan mengganti ban tepat waktu dan melakukan perawatan secara berkala,
pengendalian motor akan lebih stabil,
jarak pengereman menjadi lebih baik,
serta perjalanan menjadi lebih aman dan nyaman.
</p>

