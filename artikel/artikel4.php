<h1>Cara Merawat Aki Motor Agar Awet</h1>

<p>
Aki merupakan sumber tenaga listrik utama pada sepeda motor. Komponen ini
berfungsi untuk menghidupkan starter, lampu, klakson, panel indikator,
hingga sistem injeksi pada motor modern.
</p>

<p>
Apabila kondisi aki mulai melemah, motor akan sulit distarter,
lampu menjadi redup, bahkan mesin bisa gagal hidup.
Oleh karena itu, perawatan aki harus dilakukan secara rutin.
</p>

<div class="info">

<h3>Tips Merawat Aki</h3>

<ul>

<li>Gunakan motor secara rutin agar aki tetap terisi.</li>

<li>Matikan seluruh lampu ketika mesin tidak hidup.</li>

<li>Bersihkan terminal aki dari karat.</li>

<li>Periksa tegangan aki secara berkala.</li>

<li>Gunakan charger aki apabila motor lama tidak digunakan.</li>

</ul>

</div>

<p>
Untuk motor dengan aki basah, pastikan air aki selalu berada pada batas
yang dianjurkan. Jangan sampai air aki habis karena dapat merusak sel aki.
Sedangkan pada aki MF (Maintenance Free), cukup lakukan pengecekan
tegangan menggunakan alat ukur.
</p>

<p>
Rata-rata umur aki berkisar antara 2 hingga 3 tahun tergantung pemakaian.
Jika starter mulai berat, klakson melemah, atau lampu mulai redup,
sebaiknya segera lakukan pemeriksaan di bengkel.
</p>

<p>
Mengganti aki sebelum benar-benar rusak dapat mencegah motor mogok
secara tiba-tiba dan membuat seluruh sistem kelistrikan bekerja dengan baik.
</p>

